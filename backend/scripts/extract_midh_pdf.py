def extract_pincode(text: str) -> str:
    match = re.search(r"\b(4\d{5})\b", text)
    if match:
        return match.group(1)
    # Check Marathi numerals (४XXXXX)
    marathi_digits = str.maketrans("०१२३४५६७८९", "0123456789")
    ascii_text = text.translate(marathi_digits)
    match = re.search(r"\b(4\d{5})\b", ascii_text)
    return match.group(1) if match else ""

def extract_taluka(text: str, default_district: str) -> str:
    # Try looking for "ता.- <name>" or "ता. <name>" or "तालुका - <name>"
    for mr_term, en_term in TALUKA_KEYWORDS:
        if mr_term in text:
            return en_term
    return ""

def extract_facility_name(raw: str) -> str:
    # Remove leading "मे. ", "मेसर्स ", "श्री. "
    cleaned = raw.strip()
    # If there is a comma before address (e.g. "मे. एक्स, मु.पो. वाय")
    parts = cleaned.split(",")
    first_part = parts[0].strip()
    # Normalize prefix
    first_part = re.sub(r"^(मे\.|मेसर्स|मे\s|मै\.)\s*", "", first_part)
    return first_part

def process_records() -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    processed = []
    seen_names: Dict[str, List[int]] = {}

    for row in RAW_PDF_RECORDS:
        sr_no, dist_mr, year, raw_text, subsidy, cap, page = row
        project_id = f"MIDH-MH-{sr_no:03d}"
        dist_en = DISTRICT_MAPPING.get(dist_mr, dist_mr)
        pincode = extract_pincode(raw_text)
        taluka = extract_taluka(raw_text, dist_en)
        fac_name = extract_facility_name(raw_text)

        # Review & Duplicate detection
        review_flags = []
        is_expansion = "विस्तारीकरण" in raw_text or "जवस्तारीकरण" in raw_text
        if is_expansion:
            review_flags.append("Capacity Expansion Phase (विस्तारीकरण)")
        if cap < 100.0:
            review_flags.append("Low Capacity Pilot (<100 MT)")
        if not taluka:
            review_flags.append("Taluka not explicitly tagged in source text")

        # Duplicate checking across normalized names
        norm_key = re.sub(r"\s+", "", fac_name.lower())[:15]
        if norm_key in seen_names:
            seen_names[norm_key].append(sr_no)
            review_flags.append(f"Potential duplicate/expansion of Sr No {seen_names[norm_key][0]}")
        else:
            seen_names[norm_key] = [sr_no]

        rec = {
            "project_id": project_id,
            "sr_no": sr_no,
            "district_raw": dist_mr,
            "district_normalized": dist_en,
            "financial_year": year,
            "beneficiary_name_raw": fac_name,
            "address_raw": raw_text,
            "taluka_normalized": taluka if taluka else dist_en,
            "pincode": pincode,
            "subsidy_disbursed_lakh_inr": subsidy,
            "capacity_mt": cap,
            "source_document": "Maharashtra State MIDH Cold Storage & Integrated Cold Chain Beneficiaries List (2005-06 to 2022-23)",
            "source_page": page,
            "record_type": "Government Subsidy Project",
            "operational_status": "unverified_historical_project",
            "verification_status": "government_listed_project",
            "review_flags": "; ".join(review_flags) if review_flags else "Clean",
            "notes": f"Historical project record from MIDH Scheme list (Page {page}). Disbursed subsidy ₹{subsidy} Lakhs."
        }
        processed.append(rec)

    metrics = {
        "total_records": len(processed),
        "total_capacity_mt": round(sum(r["capacity_mt"] for r in processed), 2),
        "total_subsidy_lakh": round(sum(r["subsidy_disbursed_lakh_inr"] for r in processed), 2),
        "records_with_review_flags": sum(1 for r in processed if r["review_flags"] != "Clean"),
        "districts_covered": len(set(r["district_normalized"] for r in processed))
    }

    return processed, metrics

def export_staging_csv():
    records, metrics = process_records()
    fieldnames = [
        "project_id", "sr_no", "district_raw", "district_normalized", "financial_year",
        "beneficiary_name_raw", "address_raw", "taluka_normalized", "pincode",
        "subsidy_disbursed_lakh_inr", "capacity_mt", "source_document", "source_page",
        "record_type", "operational_status", "verification_status", "review_flags", "notes"
    ]

    with open(OUTPUT_STAGING_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, quoting=csv.QUOTE_MINIMAL)
        writer.writeheader()
        writer.writerows(records)

    print(f"Exported {len(records)} MIDH cold-chain records to {OUTPUT_STAGING_CSV}")
    print("Summary Metrics:")
    for k, v in metrics.items():
        print(f"  - {k}: {v}")

if __name__ == "__main__":
    export_staging_csv()
